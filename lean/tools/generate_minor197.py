"""Emit Brent/Formal/SmoothLeftMinorData.lean: the 197 group parameters and 197 free variables
(in an order where the tangent minor at q_L is lower triangular with diagonal ±1).
Input: wip/pick197.txt, lines `repr(param)|variableNumber`, as written by wip/pick197.py."""
import sys, bisect
cols=sorted(int(x) for x in open('wip/cols.txt'))
pairs=[l.strip().split('|') for l in open(sys.argv[1] if len(sys.argv)>1 else 'wip/pick197.txt') if l.strip()]
assert len(pairs)==197
out=['import Brent.Formal.SmoothLeftData','','/-! Generated by `tools/generate_minor197.py`. -/','',
'namespace Brent.Formal.SmoothLeftMinor','','open Brent Brent.Formal','',
'/-- The 197 chosen group parameters. -/',
'def params : Fin 197 → GrpIdx := !['+',\n  '.join(w for w,_ in pairs)+']','',
'/-- The numbers of the 197 free variables, in triangular order. -/',
'def freeNum : Fin 197 → Fin 2352 := !['+', '.join(c for _,c in pairs)+']','',
'/-- For each free variable, the number of pivot columns below it. -/',
'def pos : Fin 197 → ℕ := !['+', '.join(str(bisect.bisect_left(cols,int(c))) for _,c in pairs)+']','',
'end Brent.Formal.SmoothLeftMinor','']
open('Brent/Formal/SmoothLeftMinorData.lean','w').write('\n'.join(out))
