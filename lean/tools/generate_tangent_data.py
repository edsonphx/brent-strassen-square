"""Pack the frozen tangent frame and its signed elimination trace."""

import numpy as np

from generate_jacobian_trace import LEAN_ROOT, SOURCE_ROOT, emit_chunked_array, pack_row, sparse_row, trace


def main():
    with np.load(SOURCE_ROOT / "data" / "tangent_bases.npz", allow_pickle=False) as arrays:
        rows = np.concatenate([arrays[name] for name in ("G", "X", "Y")]).reshape(251, 2352)
    reduced, operations, pivots = trace(rows)
    indices = {i: j for j, (_, i) in enumerate(pivots)}
    columns = [
        ("tangentData", "Nat", [pack_row(sparse_row(row).items()) for row in rows]),
        ("tangentReducedData", "Nat", [pack_row(row.items()) for row in reduced]),
        ("tangentOperationsData", "Nat", [pack_row(row) for row in operations]),
        ("tangentSelectData", "Fin 251", [str(i) for _, i in pivots]),
        ("tangentPivotData", "Fin 2352", [str(j) for j, _ in pivots]),
        ("tangentCoverData", "Option (Fin 251)",
         [f"some {indices[i]}" if i in indices else "none" for i in range(len(rows))]),
    ]
    output = [
        "import Brent.SparseRow",
        "",
        "/- Generated by lean/tools/generate_tangent_data.py. -/",
        "set_option maxRecDepth 8192",
        "",
        "namespace Brent.TangentData",
        "",
    ]
    for name, ty, items in columns:
        output.extend(emit_chunked_array(name, ty, items))
    output.extend(("end Brent.TangentData", ""))
    (LEAN_ROOT / "Brent/Generated/TangentData.lean").write_text("\n".join(output))


if __name__ == "__main__":
    main()
