#!/usr/bin/env python3
"""Generate the Lean data for the AlphaTensor catalogue census (Brent.Catalogue).

Usage (from the bundle root):
    python -I scripts/gen_catalogue_lean.py data/alphatensor_14236_factorizations.npz project

Checks the SHA-256 of the npz, then (deterministically, overwriting) writes under
project/Brent/Catalogue/:
  Data/D###.lean    packed factor data, CHUNK points per file; Data.lean joins them
  Cert/C###.lean    rank and anchor certificates, CHUNK points per file; Cert.lean joins them
  Expected.lean     the predicted exceptional index sets (87 rank-bound failures, 2 anchor failures)
  Check/K###.lean   one kernel check (`decide +kernel`) per chunk
  NegData.lean      non-compatibility witnesses for the two anchor-test failures
  Checks.lean       imports every chunk check and assembles them

Packing of a point `p`: the natural number whose hexadecimal digit `k = 16 * (3 * s + m) + 4 * i + j`
(least significant first) is `factorizations[p, s, m, 4 * i + j] + 4`.  The layout of the
certificate numbers is documented in Brent/Catalogue/Kernel.lean.

Nothing produced here is trusted by Lean: every predicted fact is re-checked by the kernel
(`decide +kernel`), and the meaning of the checks is proved in Brent/Catalogue/Sound.lean.
"""
import hashlib
import itertools
import sys
from pathlib import Path

import numpy as np

SHA256 = "15d27e300a68868710c2f5824f7987b10e004c6d7de6a3e65ae35caf42ed06a3"
NPOINTS = 14236
CHUNK = 128
SUB = 4  # points per kernel-checked declaration
PRIME_Q = 65521  # exceeds the Hadamard bound 4096 for minors of 4x4 matrices with |entries| <= 4
HEADER = "-- Generated by scripts/gen_catalogue_lean.py; do not edit.\n"


def load(path: Path) -> np.ndarray:
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        raise SystemExit(f"SHA-256 mismatch: {digest}")
    with np.load(path, allow_pickle=False) as src:
        f = src["factorizations"]
    if f.shape != (NPOINTS, 49, 3, 16):
        raise SystemExit(f"unexpected shape {f.shape}")
    if f.min() < -4 or f.max() > 4:
        raise SystemExit("entries outside [-4, 4]")
    return f.astype(np.int64)


# ---------------------------------------------------------------- ranks over F_p (prediction only)

def ranks(mats: np.ndarray, p: int) -> np.ndarray:
    """Ranks of a batch of (rows x cols) integer matrices over F_p."""
    a = mats.astype(np.int64) % p
    n, rows, cols = a.shape
    r = np.zeros(n, dtype=np.int64)
    ids = np.arange(n)
    for c in range(cols):
        cand = (a[:, :, c] != 0) & (np.arange(rows)[None, :] >= r[:, None])
        has = cand.any(axis=1)
        sel = ids[has]
        if len(sel) == 0:
            continue
        pr, rr = cand.argmax(axis=1)[sel], r[sel]
        tmp = a[sel, pr].copy()
        a[sel, pr] = a[sel, rr]
        a[sel, rr] = tmp
        inv = np.array([pow(int(x), p - 2, p) for x in a[sel, rr, c]], dtype=np.int64)
        prow = a[sel, rr] * inv[:, None] % p
        a[sel, rr] = prow
        for i in range(rows):
            m = i != rr
            s2 = sel[m]
            a[s2, i] = (a[s2, i] - a[s2, i, c][:, None] * prow[m]) % p
        r[sel] += 1
    return r


def full_profile(r: np.ndarray) -> np.ndarray:
    diag = (r == r[:, :, :1]).all(axis=2)
    prof = r[:, :, 0]
    return (diag.all(axis=1) & ((prof == 1).sum(1) == 36) & ((prof == 2).sum(1) == 12)
            & ((prof == 4).sum(1) == 1))


def rank_bounds(r: np.ndarray) -> np.ndarray:
    mx = r.max(axis=2)
    return ((mx > 1).sum(1) <= 13) & ((mx > 2).sum(1) <= 1)


# ---------------------------------------------------------------- exact formulas (mirror Kernel.lean)

def det3(a, b, c, d, e, f, g, h, k):
    return a * (e * k - f * h) - b * (d * k - f * g) + c * (d * h - e * g)


def det4(M):
    m = lambda i, j: M[..., i, j]
    return (m(0, 0) * det3(m(1, 1), m(1, 2), m(1, 3), m(2, 1), m(2, 2), m(2, 3), m(3, 1), m(3, 2), m(3, 3))
            - m(0, 1) * det3(m(1, 0), m(1, 2), m(1, 3), m(2, 0), m(2, 2), m(2, 3), m(3, 0), m(3, 2), m(3, 3))
            + m(0, 2) * det3(m(1, 0), m(1, 1), m(1, 3), m(2, 0), m(2, 1), m(2, 3), m(3, 0), m(3, 1), m(3, 3))
            - m(0, 3) * det3(m(1, 0), m(1, 1), m(1, 2), m(2, 0), m(2, 1), m(2, 2), m(3, 0), m(3, 1), m(3, 2)))


def minor_det(M, I, J):
    r = len(I)
    if r == 0:
        return 1
    if r == 1:
        return int(M[I[0]][J[0]])
    if r == 2:
        return int(M[I[0]][J[0]] * M[I[1]][J[1]] - M[I[0]][J[1]] * M[I[1]][J[0]])
    if r == 3:
        return int(det3(*[M[I[a]][J[b]] for a in range(3) for b in range(3)]))
    return int(det4(np.asarray(M)))


def schur_ok(M, I, J, q):
    """delta * M == M[:, J] adj(D) M[I, :] (mod q; q = 0 exact) with the integer adjugate."""
    r = len(I)
    if r == 4:
        return True
    M = [[int(x) for x in row] for row in M]
    if r == 0:
        return all(M[i][j] % q == 0 if q else M[i][j] == 0 for i in range(4) for j in range(4))
    D = [[M[I[a]][J[b]] for b in range(r)] for a in range(r)]
    det = lambda A: (A[0][0] if len(A) == 1 else
                     A[0][0] * A[1][1] - A[0][1] * A[1][0] if len(A) == 2 else
                     det3(*[A[a][b] for a in range(3) for b in range(3)]))
    delta = det(D)
    # cofactor C[a][b]
    C = [[(1 if r == 1 else (-1) ** (a + b) * det([[D[u][v] for v in range(r) if v != b]
                                                    for u in range(r) if u != a]))
          for b in range(r)] for a in range(r)]
    for i in range(4):
        for j in range(4):
            rhs = sum(M[I[a]][j] * C[a][b] * M[i][J[b]] for a in range(r) for b in range(r))
            v = delta * M[i][j] - rhs
            if (v % q if q else v) != 0:
                return False
    return True


COMBOS = {r: list(itertools.combinations(range(4), r)) for r in range(5)}


def pivot(M, r, q, prefer3):
    """First (I, J) (rows, then columns, lexicographic) with det nonzero in char q
    (and, if prefer3, nonzero mod 3 as well when possible)."""
    if r == 0:
        return ((), ())
    best = None
    for I in COMBOS[r]:
        for J in COMBOS[r]:
            d = minor_det(M, list(I), list(J))
            ok = (d % q != 0) if q else (d != 0)
            if not ok:
                continue
            if prefer3 and d % 3 != 0:
                return (I, J)
            if best is None:
                best = (I, J)
            if not prefer3:
                return best
    return best


def enc(r, I, J):
    c = r
    for k, i in enumerate(I[:3]):
        c |= i << (3 + 2 * k)
    for k, j in enumerate(J[:3]):
        c |= j << (9 + 2 * k)
    return c


def matrix_code(M, rq, rf):
    I, J = pivot(M, rq, 0, rq == rf)
    assert schur_ok(M, list(I), list(J), 0)
    dq = minor_det(M, list(I), list(J))
    assert dq != 0
    c = enc(rq, I, J)
    if rq == rf and dq % 3 != 0:
        return c | (1 << 15)
    I3, J3 = pivot(M, rf, 3, False)
    assert schur_ok(M, list(I3), list(J3), 3)
    assert minor_det(M, list(I3), list(J3)) % 3 != 0
    return c | (enc(rf, I3, J3) << 16)


# ---------------------------------------------------------------- anchors

def span2(T, A, i0, i1, j0, j1, r, j):
    d = A[i0][j0] * A[i1][j1] - A[i0][j1] * A[i1][j0]
    return d * T[r][j] - (T[r][j0] * (A[i1][j1] * A[i0][j] - A[i0][j1] * A[i1][j]) +
                          T[r][j1] * (A[i0][j0] * A[i1][j] - A[i1][j0] * A[i0][j]))


def dec(c):
    return (c & 7, [(c >> (3 + 2 * k)) & 3 for k in range(3)], [(c >> (9 + 2 * k)) & 3 for k in range(3)])


def compat(F, codes, t, a):
    """Exactly the kernel's `compat`."""
    for m in range(3):
        T, A = F[t][m], F[a][m]
        _, It, Jt = dec(codes[t][m])
        _, Ia, Ja = dec(codes[a][m])
        Tt = [[T[j][i] for j in range(4)] for i in range(4)]
        At = [[A[j][i] for j in range(4)] for i in range(4)]
        if any(span2(T, A, Ia[0], Ia[1], Ja[0], Ja[1], It[0], j) != 0 for j in range(4)):
            return False
        if any(span2(Tt, At, Ja[0], Ja[1], Ia[0], Ia[1], Jt[0], i) != 0 for i in range(4)):
            return False
    return True


def assign(r1, cand, comp):
    """Assign every rank-one summand to one of six anchors, six each, compatibly."""
    for anchors in itertools.combinations(cand, 6):
        match = {}
        load_ = {a: [] for a in anchors}

        def aug(t, seen):
            for a in anchors:
                if comp[(t, a)] and a not in seen:
                    seen.add(a)
                    if len(load_[a]) < 6:
                        load_[a].append(t); match[t] = a
                        return True
                    for t2 in list(load_[a]):
                        if aug(t2, seen):
                            load_[a].remove(t2); load_[a].append(t); match[t] = a
                            return True
            return False

        if all(aug(t, set()) for t in r1):
            return list(anchors), match
    return None


# ---------------------------------------------------------------- non-compatibility witnesses

def null2(A, I, J):
    """Integer basis of the right kernel of a rank-two A with pivot A[I, J]."""
    a, b, c, d = A[I[0]][J[0]], A[I[0]][J[1]], A[I[1]][J[0]], A[I[1]][J[1]]
    delta = a * d - b * c
    out = []
    for f in range(4):
        if f in J[:2]:
            continue
        x0, x1 = A[I[0]][f], A[I[1]][f]
        n = [0, 0, 0, 0]
        n[f] = delta
        n[J[0]] = -(d * x0 - b * x1)
        n[J[1]] = -(-c * x0 + a * x1)
        out.append(n)
    return out


def witness(F, codes, t, a, q):
    """(m, side, row, n): `A n = 0` mod q on `side` (0 rows, 1 columns) and row `row` of T
    (resp. its transpose) has nonzero product with `n` mod q."""
    z = (lambda x: x % q == 0) if q else (lambda x: x == 0)
    for m in range(3):
        for side in (0, 1):
            T, A = F[t][m], F[a][m]
            if side:
                T = [[T[j][i] for j in range(4)] for i in range(4)]
                A = [[A[j][i] for j in range(4)] for i in range(4)]
            _, Ia, Ja = dec(codes[a][m])
            I, J = (Ja, Ia) if side else (Ia, Ja)
            basis = null2(A, I, J)
            cands = basis + [[x + y for x, y in zip(basis[0], basis[1])],
                             [x - y for x, y in zip(basis[0], basis[1])]]
            for n in cands:
                if not all(z(sum(A[i][j] * n[j] for j in range(4))) for i in range(4)):
                    continue
                for row in range(4):
                    if not z(sum(T[row][j] * n[j] for j in range(4))):
                        if max(abs(x) for x in n) < 128:
                            return (m, side, row, n)
    return None


# ---------------------------------------------------------------- emission

def pack(point: np.ndarray) -> str:
    digits = (point.reshape(-1) + 4).tolist()
    assert len(digits) == 49 * 3 * 16 and all(0 <= d <= 8 for d in digits)
    return "0x" + "".join("%x" % d for d in reversed(digits))


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def emit_lists(cat: Path, sub: str, prefix: str, values, doc: str, extra_import: str = "") -> int:
    nchunks = (NPOINTS + CHUNK - 1) // CHUNK
    for c in range(nchunks):
        lo, hi = c * CHUNK, min(NPOINTS, (c + 1) * CHUNK)
        body = ",\n  ".join(values[lo:hi])
        write(cat / sub / f"{prefix.upper()}{c:03d}.lean",
              HEADER + f"namespace Brent.Catalogue.{sub}\n\n"
              f"/-- {doc} {lo} to {hi - 1}. -/\n"
              f"def {prefix}{c:03d} : List Nat := [\n  {body}]\n\nend Brent.Catalogue.{sub}\n")
    imports = "".join(f"import Brent.Catalogue.{sub}.{prefix.upper()}{c:03d}\n" for c in range(nchunks))
    names = ", ".join(f"{prefix}{c:03d}" for c in range(nchunks))
    write(cat / f"{sub}.lean", HEADER + imports + f"""
namespace Brent.Catalogue.{sub}

/-- The chunks, `{CHUNK}` points per chunk. -/
def chunks : List (List Nat) := [{names}]

end Brent.Catalogue.{sub}
""")
    return nchunks


def main():
    npz, proj = Path(sys.argv[1]), Path(sys.argv[2])
    cat = proj / "Brent" / "Catalogue"
    f = load(npz)
    F = f.reshape(NPOINTS, 49, 3, 4, 4)

    rq = ranks(f.reshape(-1, 4, 4), PRIME_Q).reshape(NPOINTS, 49, 3)
    rf = ranks(f.reshape(-1, 4, 4), 3).reshape(NPOINTS, 49, 3)
    fq, ff = full_profile(rq), full_profile(rf)
    assert (fq == ff).all() and (fq == rank_bounds(rq)).all() and (fq == rank_bounds(rf)).all()
    bad = sorted(np.flatnonzero(~fq).tolist())
    print("full", int(fq.sum()), "bad", len(bad))

    codes = np.zeros((NPOINTS, 49, 3), dtype=np.int64)
    FL = F.tolist()
    for p in range(NPOINTS):
        for s in range(49):
            for m in range(3):
                codes[p, s, m] = matrix_code(FL[p][s][m], int(rq[p, s, m]), int(rf[p, s, m]))
        if p % 2000 == 0:
            print("codes", p, flush=True)

    Fl = F.tolist()
    anchor_bits = {}
    neg = []
    nonclean = []
    for p in range(NPOINTS):
        if not fq[p]:
            continue
        assert all((int(codes[p, s, m]) >> 15) & 1 for s in range(49) for m in range(3)), p
        r1 = [s for s in range(49) if (rq[p, s] == 1).all()]
        r2 = [s for s in range(49) if (rq[p, s] == 2).all()]
        cl = codes[p].tolist()
        comp = {(t, a): compat(Fl[p], cl, t, a) for t in r1 for a in r2}
        useful = [a for a in r2 if sum(comp[(t, a)] for t in r1) >= 6]
        ok = len(useful) >= 6 and all(any(comp[(t, a)] for a in useful) for t in r1)
        if not ok:
            neg.append(p)
            continue
        res = assign(r1, useful, comp)
        assert res is not None, p
        anchors, match = res
        if len(useful) != 6 or any(sum(comp[(t, a)] for a in useful) != 1 for t in r1):
            nonclean.append(p)
        bits = 0
        for g, a in enumerate(anchors):
            bits |= a << (6 * g)
        for t in range(49):
            g = anchors.index(match[t]) if t in match else 7
            bits |= g << (36 + 3 * t)
        anchor_bits[p] = bits
    print("anchor failures", neg, "non-clean partitions", nonclean)
    assert neg == [2445, 5969]

    certs = []
    for p in range(NPOINTS):
        C = 0
        for s in range(49):
            for m in range(3):
                C |= int(codes[p, s, m]) << (32 * (3 * s + m))
        C |= anchor_bits.get(p, 0) << 4704
        certs.append(f"0x{C:x}")

    nd = emit_lists(cat, "Data", "d", [pack(f[p]) for p in range(NPOINTS)], "Packed catalogue points")
    nc = emit_lists(cat, "Cert", "c", certs, "Certificates of points")
    assert nd == nc

    write(cat / "Expected.lean", HEADER + f"""namespace Brent.Catalogue

/-- The catalogue points failing the rank bounds (predicted; checked by the kernel). -/
def bad87 : List Nat := {bad}

/-- The full-profile catalogue points failing the anchor test (predicted; checked). -/
def neg2 : List Nat := {neg}

end Brent.Catalogue
""")

    # witnesses for the anchor failures, per field
    wl = []
    for p in neg:
        r1 = [s for s in range(49) if (rq[p, s] == 1).all()]
        r2 = [s for s in range(49) if (rq[p, s] == 2).all()]
        cl = codes[p].tolist()
        for q in (0, 3):
            items = []
            for a in r2:
                for t in r1:
                    if compat(Fl[p], cl, t, a):
                        continue
                    w = witness(Fl[p], cl, t, a, q)
                    if w is None:
                        continue
                    m, side, row, n = w
                    items.append(f"⟨{t}, {a}, {m}, {side}, {row}, {n[0]}, {n[1]}, {n[2]}, {n[3]}⟩")
            wl.append((p, q, r1, r2, items))
    body = []
    for p, q, r1, r2, items in wl:
        nm = f"w{p}_{'Q' if q == 0 else 'F'}"
        body.append(f"/-- Non-compatibility witnesses at point {p} in characteristic {q}. -/\n"
                    f"def {nm} : List Wit := [\n  " + ",\n  ".join(items) + "]\n")
        body.append(f"def r1_{p} : List Nat := {r1}\ndef r2_{p} : List Nat := {r2}\n")
    write(cat / "NegData.lean", HEADER + """namespace Brent.Catalogue

/-- A non-compatibility witness `(t, a, m, side, row, n)`: on `side` (0 rows, 1 columns), the
vector `n` is orthogonal to every row of `A = F a m` (resp. of its transpose) but not to row
`row` of `T = F t m` (resp. of its transpose). -/
structure Wit where
  t : Nat
  a : Nat
  m : Nat
  side : Nat
  row : Nat
  n0 : Int
  n1 : Int
  n2 : Int
  n3 : Int

""" + "\n".join(dict.fromkeys(body)) + "\nend Brent.Catalogue\n")

    # chunk checks
    for c in range(nd):
        lo, hi = c * CHUNK, min(NPOINTS, (c + 1) * CHUNK)
        # one declaration per SUB points: the kernel's evaluation cache is per declaration
        # Chaining uses `rangeOK_join` with every size a literal and two `rfl` side conditions,
        # so elaboration never has to solve `?n + ?n' = N` or unfold `rangeOK`.
        parts, expr, acc = [], None, 0
        for k, a in enumerate(range(lo, hi, SUB)):
            n = min(SUB, hi - a)
            parts.append(f"set_option maxHeartbeats 0 in\nset_option maxRecDepth 100000 in\n"
                         f"theorem chunk{c:03d}_{k:02d} : rangeOK {a} {n} = true := by decide +kernel\n")
            name = f"chunk{c:03d}_{k:02d}"
            expr = name if expr is None else \
                f"(rangeOK_join {lo} {acc} {a} {n} {acc + n} rfl rfl {expr}\n    {name})"
            acc += n
        write(cat / "Check" / f"K{c:03d}.lean", HEADER + "import Brent.Catalogue.Point\n\n"
              "namespace Brent.Catalogue\n\n" + "\n".join(parts) +
              f"\nset_option maxHeartbeats 0 in\nset_option maxRecDepth 100000 in\n"
              f"theorem chunk{c:03d} : rangeOK {lo} {hi - lo} = true :=\n  {expr}\n\nend Brent.Catalogue\n")
    imports = "".join(f"import Brent.Catalogue.Check.K{c:03d}\n" for c in range(nd))
    expr, acc = "chunk000", min(NPOINTS, CHUNK)
    for c in range(1, nd):
        lo, hi = c * CHUNK, min(NPOINTS, (c + 1) * CHUNK)
        expr = f"(rangeOK_join 0 {acc} {lo} {hi - lo} {acc + hi - lo} rfl rfl {expr}\n    chunk{c:03d})"
        acc += hi - lo
    write(cat / "Checks.lean", HEADER + imports + f"""
namespace Brent.Catalogue

/-- All {NPOINTS} points pass `pointOK`. -/
set_option maxHeartbeats 0 in
set_option maxRecDepth 100000 in
theorem all_points : rangeOK 0 {NPOINTS} = true :=
  {expr}

end Brent.Catalogue
""")
    print("chunks", nd)


if __name__ == "__main__":
    main()
