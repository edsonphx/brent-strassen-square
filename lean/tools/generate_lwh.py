"""Emit the generated Lean files for the Li-Wang-Hu point (F19).

Usage: python3 tools/generate_lwh.py OUTDIR
OUTDIR holds lwh_point.json, lwh_trace.json, lwh_kernel.json, lwh_orbit.json written by
tools/lwh_certificate.py. Writes
  Brent/Generated/LWHData.lean            point, trace, kernel and orbit data
  Brent/Generated/LWHBlocks/L{0..5}.lean   kernel batches for the mod-3 rank trace
  Brent/Generated/LWHChecks.lean          `checked : ∀ i, checkAt i = true`
  Brent/Generated/LWHKernelChecks.lean    `kerChecked : ∀ i, kerCheckAt i = true`
  Brent/Generated/LWHSolves.lean          the 4096 Brent identities in 16 kernel batches
"""
import json, sys
from pathlib import Path

LEAN = Path(__file__).resolve().parents[1]
BATCH = 8


def pack(items, vbits=8):
    p = 0
    for i, (k, v) in enumerate(items):
        assert 0 <= k < 65536 and 0 < abs(v) < 2 ** (vbits - 1)
        p |= ((k << vbits) | (2 * abs(v) + (v < 0))) << (24 * i)
    return hex(p)


def chunked(name, ty, items, width=48):
    out, chunks = [], []
    for o in range(0, len(items), width):
        c = f"{name}Block{o // width}"
        out += [f"private def {c} : Array ({ty}) := #[", "  " + ",\n  ".join(items[o:o + width]), "]", ""]
        chunks.append(c)
    out += [f"def {name} : Array (Array ({ty})) :=", "  #[" + ", ".join(chunks) + "]", ""]
    return out


def column_bound(point, n):
    """coordinateBound of the sparse Jacobian column of variable number n."""
    s, m, a = n // 48, (n % 48) // 16, n % 16
    f = [point[48 * s + 16 * k: 48 * s + 16 * k + 16] for k in range(3)]
    o = [f[k] for k in range(3) if k != m]
    return sum(abs(x) for x in o[0]) * sum(abs(y) for y in o[1])


def main(src):
    src = Path(src)
    point = json.load(open(src / "lwh_point.json"))
    t = json.load(open(src / "lwh_trace.json"))
    k = json.load(open(src / "lwh_kernel.json"))
    o = json.load(open(src / "lwh_orbit.json"))
    C, E = t["C"], t["E"]
    assert len(C) == 2155 and len(E) == 2155 and C == sorted(C) and E == sorted(E)
    piv = {int(a): b for a, b in t["piv"].items()}
    select = [piv[e] for e in E]
    index = {r: j for j, r in enumerate(select)}
    rowpos = {c: i for i, c in enumerate(C)}
    free = k["free"]
    assert free == sorted(free) and len(free) == 197
    import bisect
    pos = [bisect.bisect_left(C, f) for f in free]
    kerpiv = []
    for f, row in zip(free, k["kernel"]):
        rest = [(rowpos[x], v) for x, v in row if x != f]
        assert all(x in rowpos for x, v in row if x != f) and dict(row)[f] == 1
        kerpiv.append(rest)
    kbound = max(sum(abs(v) * column_bound(point, x) for x, v in row) for row in k["kernel"])
    kbits = max(8, kbound.bit_length() + 1)
    print("kernel radix bound", kbound, "bits", kbits)

    kept, coords, excluded, rels = o["kept"], o["coords"], o["excluded"], o["relations"]
    assert excluded == [0, 16, 32]
    # relCoeff g m: orbit generator `excluded[g]` = sum_m relCoeff g m * generator m.
    rel_dense = []
    for g, r in enumerate(rels):
        r = {int(a): v for a, v in r.items()}
        assert r[excluded[g]] == 1
        rel_dense.append([0 if m == excluded[g] else -r.get(m, 0) for m in range(146)])
        assert all(m in kept for m in range(146) if rel_dense[g][m] != 0)

    ns = "Brent.LWH"
    out = ["import Brent.SparseRow", "", "/- Generated by lean/tools/generate_lwh.py. -/",
           "set_option maxRecDepth 8192", "set_option maxHeartbeats 6000000", "", f"namespace {ns}", ""]
    out += chunked("pointData", "Int", [str(x) for x in point])
    out += chunked("columnData", "Nat", [str(x) for x in C])
    out += chunked("pivotData", "Nat", [str(x) for x in E])
    out += chunked("selectData", "Nat", [str(x) for x in select])
    out += chunked("indexData", "Nat", [str(index[i]) for i in range(2155)])
    out += chunked("reducedData", "Nat", [pack(r) for r in t["reds"]])
    out += chunked("operationsData", "Nat", [pack(r) for r in t["ops"]])
    out += chunked("correctionData", "Nat", [pack(r) for r in t["corrs"]])
    out += chunked("kernelData", "Nat", [pack(r) if r else "0" for r in kerpiv])
    out += ["/-- The numbers of the 197 free variables (the non-pivot columns), increasing. -/",
            "def freeNum : Fin 197 → Fin 2352 := ![" + ", ".join(map(str, free)) + "]", "",
            "/-- For each free variable, the number of pivot columns below it. -/",
            "def pos : Fin 197 → ℕ := ![" + ", ".join(map(str, pos)) + "]", "",
            "/-- The 143 kept orbit generators, in upper-triangular order. -/",
            "def kept : Fin 143 → Fin 146 := ![" + ", ".join(map(str, kept)) + "]", "",
            "/-- The 143 coordinates of the triangular orbit minor. -/",
            "def orbitCoordNum : Fin 143 → Fin 2352 := ![" + ", ".join(map(str, coords)) + "]", "",
            "/-- The three excluded orbit generators: the identity matrix unit `(g, 0, 0)` of each vertex. -/",
            "def excl : Fin 3 → Fin 146 := ![0, 16, 32]", "",
            "/-- `excl g` is the combination of kept generators `∑ (m, c) ∈ relList g, c • (generator m)`",
            "(the central scaling of vertex `g` equals a combination of term scalings). -/",
            "def relList : Fin 3 → List (Fin 146 × ℤ) := ![" + ",\n  ".join(
                "[" + ", ".join(f"({m}, {c})" for m, c in enumerate(r) if c) + "]" for r in rel_dense) + "]", "",
            f"/-- Radix width for the kernel checks. -/", f"def kernelBits : Nat := {kbits}", "",
            f"end {ns}", ""]
    (LEAN / "Brent/Generated/LWHData.lean").write_text("\n".join(out))

    # rank trace batches (same layout as generate_smooth_trace.py)
    n = 2155
    nb = (n + BATCH - 1) // BATCH
    blocks = 6
    per = (nb + blocks - 1) // blocks
    (LEAN / "Brent/Generated/LWHBlocks").mkdir(parents=True, exist_ok=True)
    for b in range(blocks):
        lines = ["import Brent.LWH.Trace", "", "/- Generated bounded-size batches for the mod-3 trace. -/",
                 f"namespace {ns}", "", "set_option maxRecDepth 32768", "set_option maxHeartbeats 0", ""]
        for q in range(b * per, min(nb, (b + 1) * per)):
            lines += [f"theorem steps{q} (j : Fin {BATCH}) : checkAt (Fin.ofNat {nb * BATCH} ({q * BATCH} + j.val)) = true :=",
                      f"  (by decide +kernel : ∀ j : Fin {BATCH}, checkAt (Fin.ofNat {nb * BATCH} ({q * BATCH} + j.val)) = true) j", ""]
        lines += [f"end {ns}", ""]
        (LEAN / f"Brent/Generated/LWHBlocks/L{b}.lean").write_text("\n".join(lines))
    lines = [f"import Brent.Generated.LWHBlocks.L{b}" for b in range(blocks)]
    lines += ["import Mathlib.Tactic.FinCases", "", f"namespace {ns}", "", "set_option maxRecDepth 32768", "",
              f"private theorem batch (q : Fin {nb}) (r : Fin {BATCH}) : checkAt (Fin.ofNat {nb * BATCH} (q.val * {BATCH} + r.val)) = true := by",
              "  fin_cases q"]
    lines += [f"  · exact steps{q} r" for q in range(nb)]
    lines += ["", f"theorem checked (i : Fin {nb * BATCH}) : checkAt i = true := by",
              f"  obtain ⟨⟨q, r⟩, rfl⟩ := (finProdFinEquiv (m := {nb}) (n := {BATCH})).surjective i",
              f"  have hi : finProdFinEquiv (q, r) = Fin.ofNat {nb * BATCH} (q.val * {BATCH} + r.val) := by",
              "    apply Fin.ext",
              f"    change r.val + {BATCH} * q.val = (q.val * {BATCH} + r.val) % {nb * BATCH}",
              "    omega",
              "  simpa only [hi] using batch q r", "", f"end {ns}", ""]
    (LEAN / "Brent/Generated/LWHChecks.lean").write_text("\n".join(lines))

    # kernel-vector checks: 197 rows padded to 200, batches of 8
    kn = 197
    knb = (kn + BATCH - 1) // BATCH
    lines = ["import Brent.LWH.Kernel", "import Mathlib.Tactic.FinCases", "",
             "/- Generated bounded-size batches: the 197 kernel vectors annihilate the Jacobian over ℤ. -/",
             f"namespace {ns}", "", "set_option maxRecDepth 32768", "set_option maxHeartbeats 0", ""]
    for q in range(knb):
        lines += [f"theorem kerSteps{q} (j : Fin {BATCH}) : kerCheckAt (Fin.ofNat {knb * BATCH} ({q * BATCH} + j.val)) = true :=",
                  f"  (by decide +kernel : ∀ j : Fin {BATCH}, kerCheckAt (Fin.ofNat {knb * BATCH} ({q * BATCH} + j.val)) = true) j", ""]
    lines += [f"private theorem kerBatch (q : Fin {knb}) (r : Fin {BATCH}) : kerCheckAt (Fin.ofNat {knb * BATCH} (q.val * {BATCH} + r.val)) = true := by",
              "  fin_cases q"]
    lines += [f"  · exact kerSteps{q} r" for q in range(knb)]
    lines += ["", f"theorem kerChecked (i : Fin {knb * BATCH}) : kerCheckAt i = true := by",
              f"  obtain ⟨⟨q, r⟩, rfl⟩ := (finProdFinEquiv (m := {knb}) (n := {BATCH})).surjective i",
              f"  have hi : finProdFinEquiv (q, r) = Fin.ofNat {knb * BATCH} (q.val * {BATCH} + r.val) := by",
              "    apply Fin.ext",
              f"    change r.val + {BATCH} * q.val = (q.val * {BATCH} + r.val) % {knb * BATCH}",
              "    omega",
              "  simpa only [hi] using kerBatch q r", "", f"end {ns}", ""]
    (LEAN / "Brent/Generated/LWHKernelChecks.lean").write_text("\n".join(lines))

    # Brent identity in 16 kernel batches, one per first coordinate
    lines = ["import Brent.LWH.Trace", "import Brent.SparseTensor", "import Mathlib.Tactic.FinCases", "",
             "/- Generated: the 4096 integer Brent identities at the Li–Wang–Hu point, by the kernel. -/",
             f"namespace {ns}", "", "set_option maxRecDepth 32768", "set_option maxHeartbeats 0", "",
             "/-- Row-major numbering of matrix coordinates. -/",
             "abbrev cn (n : Fin 16) : SquareVertex × SquareVertex := SparseTensor.coordinateNumber.symm n", ""]
    for a in range(16):
        lines += [f"theorem solvesRow{a} : ∀ b c : Fin 16,",
                  f"    pointDec.entry (cn {a}) (cn b) (cn c) = matrixMultiplicationEntry ℤ (cn {a}) (cn b) (cn c) := by",
                  "  decide +kernel", ""]
    lines += ["theorem solves_fin : ∀ a b c : Fin 16,",
              "    pointDec.entry (cn a) (cn b) (cn c) = matrixMultiplicationEntry ℤ (cn a) (cn b) (cn c) := by",
              "  intro a",
              "  fin_cases a",
              "  exacts [" + ", ".join(f"solvesRow{a}" for a in range(16)) + "]", "",
              "/-- **The integer Brent identity holds at the Li–Wang–Hu point.** -/",
              "theorem pointDec_solves : pointDec.Solves := by",
              "  intro a b c",
              "  have h := solves_fin (SparseTensor.coordinateNumber a) (SparseTensor.coordinateNumber b)",
              "    (SparseTensor.coordinateNumber c)",
              "  simpa only [cn, Equiv.symm_apply_apply] using h", "", f"end {ns}", ""]
    (LEAN / "Brent/Generated/LWHSolves.lean").write_text("\n".join(lines))
    print("trace batches", nb, "| kernel batches", knb)


if __name__ == "__main__":
    main(sys.argv[1])
