"""Emit candidate sparse row operations for the kernel's Jacobian-rank check."""

from pathlib import Path
import sys

import numpy as np


LEAN_ROOT = Path(__file__).resolve().parents[1]
SOURCE_ROOT = LEAN_ROOT.parent
sys.path.insert(0, str(SOURCE_ROOT))
from verify_certificate import jacobian_rows  # noqa: E402


def sparse_row(row):
    return {int(k): int(row[k]) for k in np.flatnonzero(row)}


def trace(columns):
    pivots = {}
    reduced, operations = [], []
    for i, column in enumerate(columns):
        row = sparse_row(column)
        steps = []
        while row:
            pivot = min(row)
            if pivot not in pivots:
                if abs(row[pivot]) != 1:
                    raise ValueError(f"nonunit pivot in column {i}")
                pivots[pivot] = i
                break
            j = pivots[pivot]
            old = reduced[j]
            multiplier = row[pivot] * old[pivot]
            steps.append((j, multiplier))
            for k, value in old.items():
                changed = row.get(k, 0) - multiplier * value
                if changed:
                    row[k] = changed
                else:
                    row.pop(k, None)
        reduced.append(dict(sorted(row.items())))
        operations.append(steps)
    return reduced, operations, sorted(pivots.items())


def pack_row(items):
    packed = 0
    for i, (k, v) in enumerate(items):
        if not (0 <= k < 4096 and 0 < abs(v) <= 3):
            raise ValueError(f"sparse entry exceeds the 16-bit encoding: {(k, v)}")
        code = 2 * abs(v) + (v < 0)
        packed |= ((k << 3) | code) << (16 * i)
    return hex(packed)


def emit_chunked_array(name, ty, items, width=48):
    declarations, chunks = [], []
    for offset in range(0, len(items), width):
        chunk = f"{name}Block{offset // width}"
        declarations.append(f"private def {chunk} : Array ({ty}) := #[")
        declarations.append("  " + ",\n  ".join(items[offset:offset + width]))
        declarations.extend(("]", ""))
        chunks.append(chunk)
    declarations.append(f"def {name} : Array (Array ({ty})) :=")
    declarations.extend(("  #[" + ", ".join(chunks) + "]", ""))
    return declarations


def main():
    with np.load(SOURCE_ROOT / "data/strassen_square_factors.npz", allow_pickle=False) as arrays:
        factors = np.stack([arrays[k] for k in ("U", "V", "W")], axis=1)
    reduced, operations, pivots = trace(jacobian_rows(factors))
    indices = {i: j for j, (_, i) in enumerate(pivots)}
    cover = [f"some {indices[i]}" if i in indices else "none" for i in range(len(reduced))]
    select = [str(i) for _, i in pivots]
    positions = [str(k) for k, _ in pivots]
    data = [
        ("reducedData", "Nat", [pack_row(row.items()) for row in reduced]),
        ("operationsData", "Nat", [pack_row(row) for row in operations]),
        ("selectData", "Fin 2352", select),
        ("pivotData", "Fin 4096", positions),
        ("coverData", "Option (Fin 2101)", cover),
    ]
    output = [
        "import Brent.SparseRow",
        "",
        "/- Generated by lean/tools/generate_jacobian_trace.py. This is candidate data. -/",
        "set_option maxRecDepth 8192",
        "set_option maxHeartbeats 6000000",
        "",
        "namespace Brent.JacobianTrace",
        "",
    ]
    for name, ty, values in data:
        output.extend(emit_chunked_array(name, ty, values))
    output.extend(("end Brent.JacobianTrace", ""))
    (LEAN_ROOT / "Brent/Generated/JacobianData.lean").write_text("\n".join(output))


if __name__ == "__main__":
    main()
