"""Check that Lean declaration names exist in a source tree (e.g. the pinned Mathlib).

Usage: python3 tools/check_decls.py .lake/packages/mathlib/Mathlib Name1 Namespace.Name2 ...
Prints each name with the declarations whose last component matches, or NOT FOUND.
Names generated by attributes (to_additive, simps) are not seen; grep for those.
"""
import re,sys,os
root=sys.argv[1]; names=sys.argv[2:]
files=[]
for d,_,fs in os.walk(root):
    for f in fs:
        if f.endswith('.lean'): files.append(os.path.join(d,f))
txt={f:open(f,encoding='utf-8').read() for f in files}
for n in names:
    last=n.split('.')[-1]
    pat=re.compile(r'^\s*(?:@\[[^\]]*\]\s*)?(?:protected\s+|private\s+|noncomputable\s+)*(theorem|lemma|def|abbrev|instance|structure|class)\s+(?:_root_\.)?([\w.\']*\b'+re.escape(last)+r')\b(?![\w\'])',re.M)
    hits=[]
    for f,t in txt.items():
        for m in pat.finditer(t):
            hits.append(f"{m.group(2)} @ {f.split('Mathlib/')[-1]}")
    print(f"[{n}] "+("; ".join(hits[:4]) if hits else "NOT FOUND"))
