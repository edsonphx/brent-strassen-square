"""Pack the paper's finite quadratic witnesses and integer divisibility certificates."""

from pathlib import Path

import numpy as np

from generate_jacobian_trace import LEAN_ROOT, SOURCE_ROOT, emit_chunked_array, jacobian_rows, trace


def pack_signed(items):
    packed = 0
    for position, (index, value) in enumerate(items):
        if not (0 <= index < 256 and 0 < abs(value) < 128):
            raise ValueError(f"entry exceeds packed range: {(index, value)}")
        packed |= ((index << 8) | (2 * abs(value) + (value < 0))) << (16 * position)
    return hex(packed)


def packed_columns(matrix):
    return [pack_signed((int(i), int(column[i])) for i in np.flatnonzero(column))
            for column in matrix.T]


def main():
    data = SOURCE_ROOT / "data"
    with np.load(data / "strassen_square_factors.npz", allow_pickle=False) as arrays:
        factors = np.stack([arrays[k] for k in ("U", "V", "W")], axis=1)
    with np.load(data / "regular_sequence_certificate.npz", allow_pickle=False) as cert:
        linear_forms = cert["lambda_mod3"].astype(np.int64)

    reduced, _, pivots = trace(jacobian_rows(factors))
    numerators = np.zeros((54, len(pivots)), dtype=np.int64)
    for i, (_, row_index) in enumerate(pivots):
        for column, coefficient in reduced[row_index].items():
            numerators[:, i] += coefficient * linear_forms[:, column]
    if np.any(numerators % 3):
        raise ValueError("a witness fails to annihilate a Jacobian pivot modulo 3")

    output = [
        "import Brent.SparseRow",
        "",
        "/- Generated by lean/tools/generate_quadratic_data.py. -/",
        "set_option maxRecDepth 8192",
        "",
        "namespace Brent.QuadraticData",
        "",
    ]
    output.extend(emit_chunked_array("functionalData", "Nat", packed_columns(linear_forms)))
    output.extend(emit_chunked_array("annihilatorQuotientData", "Nat",
                                      packed_columns(numerators // 3)))
    output.extend(("end Brent.QuadraticData", ""))
    (LEAN_ROOT / "Brent/Generated/QuadraticData.lean").write_text("\n".join(output))


if __name__ == "__main__":
    main()
