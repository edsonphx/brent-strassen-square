"""Pack the two frozen recursive tangent blocks and their mixed quadratic witnesses."""

import numpy as np

from generate_jacobian_trace import LEAN_ROOT, SOURCE_ROOT, emit_chunked_array
from generate_quadratic_data import pack_signed, packed_columns
from verify_certificate import mixed_row


def block_rows(directions, reverse=False):
    blocks, rows = [], []
    for vector in directions:
        factors = np.swapaxes(vector.reshape(7, 7, 3, 16), 0, 1) if reverse else vector.reshape(7, 7, 3, 16)
        indices = np.flatnonzero(np.any(factors != 0, axis=(1, 2, 3)))
        if len(indices) != 1:
            raise ValueError("a selected tangent direction is not supported on one recursive block")
        block = int(indices[0])
        blocks.append(str(block))
        for direction in factors[block].reshape(21, 16):
            rows.append(pack_signed((int(i), int(direction[i])) for i in np.flatnonzero(direction)))
    return blocks, rows


def main():
    data = SOURCE_ROOT / "data"
    with np.load(data / "strassen_square_factors.npz", allow_pickle=False) as points:
        factors = np.stack([points[k] for k in ("U", "V", "W")], axis=1)
    with np.load(data / "regular_sequence_certificate.npz", allow_pickle=False) as cert:
        covectors = cert["lambda_mod3"].astype(np.int64)
        expected = cert["quadrics_mod3"].astype(np.int64)
    with np.load(data / "tangent_bases.npz", allow_pickle=False) as basis:
        x, y = basis["X"], basis["Y"]
    x_blocks, x_rows = block_rows(x)
    y_blocks, y_rows = block_rows(y, reverse=True)

    quotients = np.empty_like(expected)
    for i, u in enumerate(x):
        for j, v in enumerate(y):
            column = mixed_row(factors, u, v)
            support = np.flatnonzero(column)
            difference = covectors[:, support] @ column[support] - expected[:, 54 * i + j]
            if np.any(difference % 3):
                raise ValueError(f"coefficient mismatch in column {(i, j)}")
            quotients[:, 54 * i + j] = difference // 3

    output = [
        "import Brent.SparseRow",
        "",
        "/- Generated by lean/tools/generate_mixed_data.py. -/",
        "set_option maxRecDepth 8192",
        "",
        "namespace Brent.QuadraticData",
        "",
    ]
    for name, ty, items in [
        ("xBlockData", "Fin 7", x_blocks),
        ("yBlockData", "Fin 7", y_blocks),
        ("xFactorData", "Nat", x_rows),
        ("yFactorData", "Nat", y_rows),
        ("mixedExpectedData", "Nat", packed_columns(expected)),
        ("mixedQuotientData", "Nat", packed_columns(quotients)),
    ]:
        output.extend(emit_chunked_array(name, ty, items))
    output.extend(("end Brent.QuadraticData", ""))
    (LEAN_ROOT / "Brent/Generated/MixedData.lean").write_text("\n".join(output))


if __name__ == "__main__":
    main()
