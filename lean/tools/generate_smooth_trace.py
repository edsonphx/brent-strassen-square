"""Emit the mod-3 elimination trace certifying a 2155 Jacobian minor at the t = 1 points.

Input: scratch JSON produced by a mod-3 elimination over the integer Jacobian columns.
Rows are `original - 3 * correction`; reduced rows and multipliers are signed units.
"""
import json, sys
from pathlib import Path

LEAN = Path(__file__).resolve().parents[1]
BATCH = 8

def pack(items, vbits=8):
    p = 0
    for i, (k, v) in enumerate(items):
        assert 0 <= k < 65536 and 0 < abs(v) < 2 ** (vbits - 1)
        p |= ((k << vbits) | (2 * abs(v) + (v < 0))) << (24 * i)
    return hex(p)

def chunked(name, ty, items, width=48):
    out, chunks = [], []
    for o in range(0, len(items), width):
        c = f"{name}Block{o // width}"
        out += [f"private def {c} : Array ({ty}) := #[", "  " + ",\n  ".join(items[o:o + width]), "]", ""]
        chunks.append(c)
    out += [f"def {name} : Array (Array ({ty})) :=", "  #[" + ", ".join(chunks) + "]", ""]
    return out

def main(src, qfile, tag):
    t = json.load(open(src))
    q = list(map(int, open(qfile).read().split()))
    n = len(t['C']); E = t['E']
    piv = {int(k): v for k, v in t['piv'].items()}
    select = [piv[e] for e in E]
    index = {r: j for j, r in enumerate(select)}
    ns = f"Brent.Smooth{tag}"
    out = ["import Brent.SparseRow", "", "/- Generated by lean/tools/generate_smooth_trace.py. -/",
           "set_option maxRecDepth 8192", "set_option maxHeartbeats 6000000", "", f"namespace {ns}", ""]
    out += chunked("pointData", "Int", [str(x) for x in q])
    out += chunked("columnData", "Nat", [str(x) for x in t['C']])
    out += chunked("pivotData", "Nat", [str(x) for x in E])
    out += chunked("selectData", "Nat", [str(x) for x in select])
    out += chunked("indexData", "Nat", [str(index[i]) for i in range(n)])
    out += chunked("reducedData", "Nat", [pack(r) for r in t['reds']])
    out += chunked("operationsData", "Nat", [pack(o) for o in t['ops']])
    out += chunked("correctionData", "Nat", [pack(c) for c in t['corrs']])
    out += [f"end {ns}", ""]
    (LEAN / f"Brent/Generated/Smooth{tag}Data.lean").write_text("\n".join(out))
    nb = (n + BATCH - 1) // BATCH
    blocks = 6
    per = (nb + blocks - 1) // blocks
    for b in range(blocks):
        lines = [f"import Brent.Smooth{tag}", "", "/- Generated bounded-size batches for the mod-3 trace. -/",
                 f"namespace {ns}", "", "set_option maxRecDepth 32768", "set_option maxHeartbeats 0", ""]
        for q_ in range(b * per, min(nb, (b + 1) * per)):
            lines += [f"theorem steps{q_} (j : Fin {BATCH}) : checkAt (Fin.ofNat {nb * BATCH} ({q_ * BATCH} + j.val)) = true :=",
                      f"  (by decide +kernel : ∀ j : Fin {BATCH}, checkAt (Fin.ofNat {nb * BATCH} ({q_ * BATCH} + j.val)) = true) j", ""]
        lines += [f"end {ns}", ""]
        (LEAN / f"Brent/Generated/SmoothBlocks/{tag}{b}.lean").write_text("\n".join(lines))
    lines = [f"import Brent.Generated.SmoothBlocks.{tag}{b}" for b in range(blocks)]
    lines += ["import Mathlib.Tactic.FinCases", "", f"namespace {ns}", "", "set_option maxRecDepth 32768", "",
              f"private theorem batch (q : Fin {nb}) (r : Fin {BATCH}) : checkAt (Fin.ofNat {nb * BATCH} (q.val * {BATCH} + r.val)) = true := by",
              "  fin_cases q"]
    lines += [f"  · exact steps{q_} r" for q_ in range(nb)]
    lines += ["", f"theorem checked (i : Fin {nb * BATCH}) : checkAt i = true := by",
              f"  obtain ⟨⟨q, r⟩, rfl⟩ := (finProdFinEquiv (m := {nb}) (n := {BATCH})).surjective i",
              f"  have hi : finProdFinEquiv (q, r) = Fin.ofNat {nb * BATCH} (q.val * {BATCH} + r.val) := by",
              "    apply Fin.ext",
              f"    change r.val + {BATCH} * q.val = (q.val * {BATCH} + r.val) % {nb * BATCH}",
              "    omega",
              "  simpa only [hi] using batch q r", "", f"end {ns}", ""]
    (LEAN / f"Brent/Generated/Smooth{tag}Checks.lean").write_text("\n".join(lines))
    print(tag, n, nb)

if __name__ == "__main__":
    main(*sys.argv[1:4])
